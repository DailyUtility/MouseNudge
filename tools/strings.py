# Adds rows to Strings.swift, which is now the translation table itself.
# Usage: python3 -I tools/strings.py Sources/Strings.swift [rows.txt]
# rows.txt: one key per line, 10 columns joined by " | ": key | zh-Hans | en | zh-Hant | ja | ko | ms | es | fr | de.
# Keys are short dotted names such as menu.subscribeHoliday. A row whose key already exists replaces it.
# With no rows file the table is just rewritten (a format check).
import json, re, sys
LANGS = ["zh-Hans", "en", "zh-Hant", "ja", "ko", "ms", "es", "fr", "de"]
path = sys.argv[1]; src = open(path, encoding="utf-8").read()
pair = re.compile(r'^        ("(?:[^"\\]|\\.)*"): ("(?:[^"\\]|\\.)*"),$')
tables, keys, lang = {l: {} for l in LANGS}, [], None
for line in src.splitlines():
    m = re.match(r'^    "([A-Za-z-]+)": \[$', line)
    if m: lang = m.group(1); continue
    if line.startswith("let translationKeys"): lang = "keys"; continue
    if lang in tables and (m := pair.match(line)): tables[lang][json.loads(m.group(1))] = json.loads(m.group(2))
    elif lang == "keys" and (m := re.match(r'^    ("(?:[^"\\]|\\.)*"),$', line)): keys.append(json.loads(m.group(1)))
if len(sys.argv) > 2:
    for n, row in enumerate(open(sys.argv[2], encoding="utf-8"), 1):
        if not row.strip(): continue
        cols = row.rstrip("\n").split(" | ")
        if len(cols) != 10: sys.exit(f"line {n}: {len(cols)} columns, need 10")
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*(\.[a-z][A-Za-z0-9]*)+", cols[0]): sys.exit(f"line {n}: key {cols[0]!r} should look like menu.more")
        if cols[0] not in keys: keys.append(cols[0])
        for l, v in zip(LANGS, cols[1:]): tables[l][cols[0]] = v
q = lambda s: json.dumps(s, ensure_ascii=False)
out = ["// Generated by tools/strings.py (one row per key, columns key/zh-Hans/en/zh-Hant/ja/ko/ms/es/fr/de). Missing keys fall back to English.",
       "let translations: [String: [String: String]] = ["]
for l in LANGS:
    out.append(f'    "{l}": [')
    out += [f"        {q(k)}: {q(tables[l][k])}," for k in keys if k in tables[l]]
    out.append("    ],")
out.append("]")
out.append("// Template order.")
out.append("let translationKeys: [String] = [")
out += [f"    {q(k)}," for k in keys]
out.append("]")
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(keys), "keys")
